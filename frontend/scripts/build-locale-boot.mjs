/**
 * Generate `public/locale-boot.js` — the language decision that happens
 * before the app exists.
 *
 * The problem it solves is small and very visible. `index.html` is a
 * static file: one `<html lang>`, one `<title>`, one description, and
 * they were Russian. A German visitor opening the site got a Russian tab
 * label and a Russian page description for as long as the bundle took to
 * load and boot — on a cold cache and a phone connection, seconds. The
 * app then corrected itself, which is exactly the "renders in one
 * language and then translates" behaviour we are removing everywhere
 * else.
 *
 * So the decision is made in a script small enough to run before the
 * first paint, using the same order the app itself uses (stored choice,
 * then browser), and it sets the three things that exist that early:
 * the lang attribute, the title, and the meta description.
 *
 * Why generated rather than hand-written: the strings belong to the
 * locale catalogs, and a second copy of them in a static file is a
 * second copy that goes stale. `npm run build` regenerates this, and
 * `scripts/i18n-check.mjs` fails if the committed file has drifted.
 *
 * Why a file rather than an inline script: the Content-Security-Policy
 * in `vercel.json` is `script-src 'self'`. An inline block would need a
 * hash kept in sync with the script by hand, which is one more thing to
 * forget; a same-origin file costs one cheap request on an HTTP/2
 * connection that is already open.
 */

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const localesDir = resolve(here, "../src/i18n/locales")
const outFile = resolve(here, "../public/locale-boot.js")

// Kept in step with SUPPORTED_LOCALES in src/i18n/config.ts. The
// i18n-check script asserts the two agree.
export const LOCALES = ["ru", "en", "de", "uk"]
// And in step with DEFAULT_LOCALE in src/i18n/config.ts. This is the same
// fact written twice — it has to be decided before the bundle exists and
// again inside it — so a disagreement here paints the first frame in one
// language and the second in another. `__tests__/localeBoot.test.ts`
// asserts the two constants are equal, and that the committed
// public/locale-boot.js carries the same value.
export const DEFAULT_LOCALE = "en"
// Must match LOCALE_STORAGE_KEY in src/i18n/config.ts — this script reads
// the choice the app wrote on a previous visit.
export const STORAGE_KEY = "equip:locale"
// And LEGACY_LOCALE_STORAGE_KEY. `src/i18n/config.ts` migrates the
// pre-rebrand key onto the current one — but it does that at module load,
// which is after this script has already painted. A returning reader who
// still had only the old key was therefore decided by their browser for one
// frame, then flipped by the bundle to the language they had actually
// chosen: exactly the "renders in one language and then translates"
// behaviour this file exists to remove, and the more jarring version of it
// because it happens to the people who have been here longest.
//
// Reading both keys here — and only reading; the migration write stays in
// config.ts, where it can fail safely — closes the window.
export const LEGACY_STORAGE_KEY = "bible-school:locale"

export function buildLocaleBoot() {
  const meta = {}
  for (const locale of LOCALES) {
    const catalog = JSON.parse(readFileSync(resolve(localesDir, `${locale}.json`), "utf8"))
    if (!catalog.meta?.documentTitle || !catalog.meta?.description) {
      throw new Error(`${locale}.json is missing meta.documentTitle / meta.description`)
    }
    meta[locale] = {
      title: catalog.meta.documentTitle,
      description: catalog.meta.description,
    }
  }

  return `// GENERATED by scripts/build-locale-boot.mjs — do not edit by hand.
// Runs before the bundle so the first frame is already in the visitor's
// language: tab label, page description, and the lang attribute that
// screen readers and browser translation toolbars read.
(function () {
  var META = ${JSON.stringify(meta, null, 2)};
  var DEFAULT = ${JSON.stringify(DEFAULT_LOCALE)};

  // The current key first, then the pre-rebrand one the bundle migrates
  // away a moment later. Without the second lookup a returning reader got
  // one frame of whatever their browser asks for before the app corrected
  // it to the language they chose.
  function stored() {
    try {
      return window.localStorage.getItem(${JSON.stringify(STORAGE_KEY)})
        || window.localStorage.getItem(${JSON.stringify(LEGACY_STORAGE_KEY)});
    } catch (e) {
      // Private mode, disabled storage, quota — not knowing is fine.
      return null;
    }
  }

  function fromBrowser() {
    var langs = (navigator.languages && navigator.languages.length)
      ? navigator.languages
      : [navigator.language];
    for (var i = 0; i < langs.length; i++) {
      var head = String(langs[i] || "").toLowerCase().split("-")[0];
      if (META[head]) return head;
    }
    return null;
  }

  // Same order as the app's own detector, so the language chosen here is
  // the language the app settles on and nothing flips a moment later.
  var locale = stored();
  if (!META[locale]) locale = fromBrowser();
  if (!META[locale]) locale = DEFAULT;

  document.documentElement.lang = locale;
  document.title = META[locale].title;

  var description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute("content", META[locale].description);
})();
`
}

export const OUT_FILE = outFile

// Only writes when run as a command. Imported — by the i18n check, which
// compares the committed file against what this would produce — it must
// not have side effects.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(outFile, buildLocaleBoot(), "utf8")
  console.log(`locale-boot.js written for ${LOCALES.join(", ")}`)
}
